async function importWatches() {
  console.log(`Importing ${watches.length} watches...`)

  const transaction = client.transaction()
  for (const watch of watches) {
    const doc = {
      _type: 'watch',
      _id: `watch-${slug(watch.name)}`,
      name: watch.name,
      slug: { _type: 'slug', current: slug(watch.name) },
      maker: watch.maker,
      reference: watch.reference || '',
      year: watch.year || '',
      caseMaterial: watch.caseMaterial || '',
      caseDiameter: watch.caseDiameter || '',
      movement: watch.movement || '',
      complications: watch.complications || '',
      filterCategory: watch.filterCategory,
      order: watch.order,
      description: watch.description,
      notes: watch.notes,
    }
    transaction.createOrReplace(doc)
  }

  try {
    const result = await transaction.commit()
    console.log(`✅ Imported ${watches.length} watches successfully`)
    console.log(`Transaction ID: ${result.transactionId}`)
  } catch (err) {
    console.error('❌ Import failed:', err.message)
    process.exit(1)
  }
}

importWatches()
