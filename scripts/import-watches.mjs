function slug(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

function key() {
  return crypto.randomBytes(6).toString('hex')
}

function text(content) {
  return [{ _type: 'block', _key: key(), style: 'normal', markDefs: [], children: [{ _type: 'span', _key: key(), text: content, marks: [] }] }]
}

